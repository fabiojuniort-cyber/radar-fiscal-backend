export function pdf(label: string): Uint8Array {
  return new TextEncoder().encode('%PDF-1.7\n' + label);
}

export function zip(label: string): Uint8Array {
  const body = new TextEncoder().encode(label);
  return Uint8Array.from([0x50, 0x4b, 0x03, 0x04, ...body]);
}
