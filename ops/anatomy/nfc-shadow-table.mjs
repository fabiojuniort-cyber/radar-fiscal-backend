import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

/**
 * ANAT-UNICODE-01b/B1 — deterministic generator of the NFC boundary table used by src/modules/anatomy/nfc-shadow.ts.
 * Inputs are the official Unicode Character Database files vendored in ops/anatomy/ucd/<version>/ (no download at
 * runtime). A code point has an NFC boundary before it when ccc = 0 and NFC_Quick_Check = Yes (UAX #15 §9); the
 * table lists the complement as sorted, merged [first, last] ranges.
 * Usage: node ops/anatomy/nfc-shadow-table.mjs [--write]   (without --write it verifies the generated files)
 */
const UNICODE_VERSION = '17.0';
const root = new URL('../../', import.meta.url);
const dir = new URL(`ops/anatomy/ucd/${UNICODE_VERSION}.0/`, root);
const inputs = ['UnicodeData.txt', 'DerivedNormalizationProps.txt', 'NormalizationTest.txt'];
const sha = (b) => createHash('sha256').update(b).digest('hex');
const raw = Object.fromEntries(inputs.map((f) => [f, readFileSync(new URL(f, dir))]));
for (const f of inputs) {
  const head = raw[f].subarray(0, 200).toString('utf8');
  if (f !== 'UnicodeData.txt' && !head.includes(`-${UNICODE_VERSION}.0.txt`)) throw new Error(`${f} is not Unicode ${UNICODE_VERSION}.0`);
}

const blocked = new Set();
for (const line of raw['UnicodeData.txt'].toString('utf8').split('\n')) {
  if (!line) continue;
  const f = line.split(';');
  // Range entries (<..., First>/<..., Last>) all have ccc 0, so only single entries matter here.
  if (Number(f[3]) !== 0) blocked.add(parseInt(f[0], 16));
}
for (const line of raw['DerivedNormalizationProps.txt'].toString('utf8').split('\n')) {
  const m = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*NFC_QC\s*;\s*([NM])\b/u.exec(line);
  if (!m) continue;
  const a = parseInt(m[1], 16); const b = m[2] ? parseInt(m[2], 16) : a;
  for (let c = a; c <= b; c++) blocked.add(c);
}
const sorted = [...blocked].sort((x, y) => x - y);
const ranges = [];
for (const c of sorted) {
  const last = ranges[ranges.length - 1];
  if (last && last[1] === c - 1) last[1] = c; else ranges.push([c, c]);
}
const flat = ranges.flat();
const inputHashes = Object.fromEntries(inputs.map((f) => [f, sha(raw[f])]));
const tableSha256 = sha(JSON.stringify(flat));
const generatorSha256 = sha(readFileSync(new URL(import.meta.url)));

const ts = `// Generated by ops/anatomy/nfc-shadow-table.mjs --write; do not edit.
// Unicode ${UNICODE_VERSION}.0 code points WITHOUT an NFC boundary before them (ccc != 0 or NFC_QC in {N, M}),
// as flattened inclusive [first, last] ranges. Table SHA-256 (JSON of the array): ${tableSha256}.
export const NFC_SHADOW_UNICODE_VERSION = '${UNICODE_VERSION}' as const;
export const NFC_SHADOW_TABLE_SHA256 = '${tableSha256}' as const;
export const NFC_NO_BOUNDARY_BEFORE: readonly number[] = Object.freeze([${flat.join(',')}]);
`;
const moduleSha256 = sha(readFileSync(new URL('src/modules/anatomy/nfc-shadow.ts', root)));
const manifest = JSON.stringify({ component: 'anatomy/nfc-shadow (UNICODE-01b/B1)',
  engineIdentity: 'not part of engineHash: no reader, extractor, engine or adapter imports this component',
  unicodeVersion: `${UNICODE_VERSION}.0`,
  source: 'Official UCD files from unicode-org/icu tag release-78.3, icu4c/source/data/unidata/ (ICU 78.3 = Unicode 17.0, the ICU of Node 24)',
  inputs: inputHashes, generator: 'ops/anatomy/nfc-shadow-table.mjs', generatorSha256,
  table: 'src/modules/anatomy/nfc-shadow-table.ts', tableSha256, ranges: ranges.length, codePoints: sorted.length,
  module: 'src/modules/anatomy/nfc-shadow.ts', moduleSha256 }, null, 1);
const tablePath = new URL('src/modules/anatomy/nfc-shadow-table.ts', root);
const manifestPath = new URL('docs/anatomy/nfc-shadow-manifest.json', root);
if (process.argv.includes('--write')) {
  writeFileSync(tablePath, ts); writeFileSync(manifestPath, `${manifest}\n`);
  console.log(`NFC shadow table written: ${ranges.length} ranges, ${sorted.length} code points, ${tableSha256}`);
} else {
  if (readFileSync(tablePath, 'utf8') !== ts) throw new Error('nfc-shadow-table.ts differs from the generator output');
  if (readFileSync(manifestPath, 'utf8') !== `${manifest}\n`) throw new Error('nfc-shadow-manifest.json differs from the generator output');
  console.log(`NFC shadow table verified: ${tableSha256}`);
}
