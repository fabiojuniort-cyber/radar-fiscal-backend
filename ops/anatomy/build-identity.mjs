import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

// Canonical source form matches Git's LF representation on Linux and Windows.
// Generated identity is excluded from its own inputs to avoid a recursive hash.
const files = ['package-lock.json', 'src/modules/anatomy/contract.ts', 'src/modules/anatomy/readers.ts', 'src/modules/anatomy/pdf-reader.ts',
  'src/modules/anatomy/entities.ts', 'src/modules/anatomy/engine.ts', 'src/modules/anatomy/consumer.ts', 'src/modules/anatomy/dou-preparation.ts', 'src/modules/anatomy/gold.ts', 'src/modules/anatomy/json-preparation.ts', 'src/modules/anatomy/sefaz-sp-preparation.ts', 'src/modules/anatomy/rfb-inline-attachments.ts', 'src/modules/anatomy/profile.ts', 'src/modules/anatomy/profile-rules.ts',
  // UNICODE-01b/B2: NFC recovery path, its Unicode 17.0 table and the component manifest (Unicode version, UCD input hashes).
  'src/modules/anatomy/nfc-recovery.ts', 'src/modules/anatomy/nfc-shadow.ts', 'src/modules/anatomy/nfc-shadow-table.ts', 'docs/anatomy/nfc-shadow-manifest.json',
  'ops/anatomy/build-identity.mjs'];
const root = new URL('../../', import.meta.url);
const digest = value => createHash('sha256').update(value, 'utf8').digest('hex');
const sourceHashes = Object.fromEntries(files.sort().map(path => [path,
  digest(readFileSync(new URL(path, root), 'utf8').replace(/\r\n/g, '\n'))]));
const sourceManifest = JSON.stringify({ normalization: 'UTF-8 source with LF line endings', sourceHashes });
const engineHash = digest(sourceManifest);
const generated = `// Generated by ops/anatomy/build-identity.mjs --write; do not edit.\nexport const ANATOMY_ENGINE_BUILD_HASH = '${engineHash}' as const;\n`;
const target = new URL('src/modules/anatomy/build-identity.ts', root);
const manifestPath = new URL('docs/anatomy/engine-build.json', root);
const manifest = JSON.stringify({ engineHash, ...JSON.parse(sourceManifest) }, null, 2) + '\n';
if (process.argv.includes('--write')) {
  writeFileSync(target, generated);
  writeFileSync(manifestPath, manifest);
  console.log(`ANAT build identity frozen: ${engineHash}`);
} else {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== generated
      || readFileSync(manifestPath, 'utf8').replace(/\r\n/g, '\n') !== manifest) {
    throw new Error('ANAT engine source identity changed; explicitly regenerate before publishing');
  }
  console.log(`ANAT build identity verified: ${engineHash}`);
}
