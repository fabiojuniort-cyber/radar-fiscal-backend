import assert from 'node:assert/strict';
import {parseRoles,renderRoles} from './prepare-restore-roles.mjs';
const sql=`ALTER TABLE public.t OWNER TO radar_owner;
GRANT SELECT ON public.t TO radar_app, "Role with space";
REVOKE ALL ON public.t FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE radar_owner GRANT SELECT ON TABLES TO radar_readonly;
CREATE POLICY p ON public.t TO radar_worker, PUBLIC USING (true);
ALTER POLICY p ON public.t TO "O'Brian";
CREATE FUNCTION f() RETURNS void AS $$ BEGIN GRANT SELECT ON t TO fake_role; END $$ LANGUAGE plpgsql;
-- ALTER TABLE t OWNER TO comment_role;
ALTER TABLE t OWNER TO postgres;`;
assert.deepEqual(parseRoles(sql),["O'Brian","Role with space","postgres","radar_app","radar_owner","radar_readonly","radar_worker"].sort());
const out=renderRoles(["O'Brian",'a"b','pg_monitor','postgres','railway']);
assert.ok(out.includes('"O\'Brian" NOLOGIN PASSWORD NULL'));
assert.ok(out.includes('"a""b" NOLOGIN PASSWORD NULL'));
assert.ok(!out.includes('CREATE ROLE "postgres"'));
assert.ok(!out.includes('CREATE ROLE "pg_monitor"'));
assert.throws(()=>parseRoles('ALTER TABLE t OWNER TO ;'));
assert.throws(()=>parseRoles('GRANT SELECT ON t TO "unfinished'));
