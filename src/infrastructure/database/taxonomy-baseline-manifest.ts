import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

import {
  MANIFEST_PATH,
} from '../../modules/taxonomy/baseline/baseline.constants.js';
import {
  manifestBytes,
  manifestSha256,
} from '../../modules/taxonomy/baseline/baseline.manifest.js';
import {
  loadBaseline,
} from '../../modules/taxonomy/baseline/baseline.source-reader.js';

const loaded = await loadBaseline();
const bytes = manifestBytes(loaded.manifest);
const write = process.argv.includes('--write');
const check = process.argv.includes('--check');

if (write && check) {
  throw new Error(
    'Use either --write or --check, not both.',
  );
}

if (write) {
  await writeFile(
    resolve(process.cwd(), MANIFEST_PATH),
    bytes,
    'utf8',
  );
}

if (check) {
  let committed: string;

  try {
    committed = await readFile(
      resolve(process.cwd(), MANIFEST_PATH),
      'utf8',
    );
  } catch {
    throw new Error(
      'BASELINE_MANIFEST_MISSING: generate with --write',
    );
  }

  if (committed !== bytes) {
    throw new Error(
      'NON_DETERMINISTIC_DERIVATION: committed manifest differs from generated bytes',
    );
  }
}

console.log(
  'TAXONOMY_BASELINE_MANIFEST=' +
    JSON.stringify({
      mode: write ? 'WRITE' : check ? 'CHECK' : 'PRINT',
      path: MANIFEST_PATH,
      manifestSha256: manifestSha256(
        loaded.manifest,
      ),
      derivationFingerprint:
        loaded.manifest.derivation.fingerprint,
      expected: loaded.manifest.expected,
      relationTypes:
        loaded.manifest.relationTypes.length,
      relationRules:
        loaded.manifest.relationRules.length,
      relations: loaded.manifest.relations.length,
    }),
);
